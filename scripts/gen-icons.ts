/**
 * Generates src/components/icon-paths.ts from Phosphor Icons (MIT) so only
 * the icons the app uses are bundled, all in one consistent weight (bold),
 * plus two fill-weight arrows for the answer buttons.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { COLLECTIONS } from '../src/data/definitions.ts';
import { ACHIEVEMENTS } from '../src/game/achievements.ts';

const UI = [
  'arrow-up', 'arrow-down', 'arrow-right', 'arrow-left', 'x', 'play', 'chart-bar', 'gear', 'calendar-check', 'timer',
  'share-network', 'copy', 'info', 'check', 'trophy', 'lightning', 'magnifying-glass', 'caret-right', 'caret-left',
  'caret-down', 'caret-up', 'lock-simple', 'sun', 'moon', 'device-mobile', 'speaker-high', 'speaker-slash', 'vibrate',
  'arrow-counter-clockwise', 'trash', 'export', 'plus-square', 'sparkle', 'medal', 'shuffle', 'crown', 'compass',
  'hand-tap', 'arrow-square-out', 'x-circle', 'check-circle', 'book-open', 'shield-check', 'warning-circle',
  'arrows-clockwise', 'squares-four', 'cloud-slash', 'list', 'circle-half',
];
const FILL = ['arrow-fat-up', 'arrow-fat-down'];

const names = [...new Set([...UI, ...COLLECTIONS.map((c) => c.icon), ...ACHIEVEMENTS.map((a) => a.icon)])].sort();
const inner = (file: string) => {
  const svg = readFileSync(file, 'utf8');
  return svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
};
const entries: string[] = [];
for (const n of names) entries.push(`  '${n}': ${JSON.stringify(inner(`node_modules/@phosphor-icons/core/assets/bold/${n}-bold.svg`))},`);
for (const n of FILL) entries.push(`  '${n}-fill': ${JSON.stringify(inner(`node_modules/@phosphor-icons/core/assets/fill/${n}-fill.svg`))},`);

writeFileSync(
  'src/components/icon-paths.ts',
  `// Generated by scripts/gen-icons.ts from Phosphor Icons (MIT licence). Do not edit.\nexport const ICON_PATHS: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`${entries.length} icons written to src/components/icon-paths.ts`);
