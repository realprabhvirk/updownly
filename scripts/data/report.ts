/**
 * `npm run data:report` — writes DATA-COVERAGE.md from the generated
 * dataset. Every number in the report is computed from the bundled files.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { ALLOWED_LICENCES, COLLECTIONS, GROUPS, METRICS, SOURCES, metricById } from '../../src/data/definitions.ts';
import { validateDataset } from '../../src/data/validate.ts';
import { loadGenerated } from './lib/load-generated.ts';

const { manifest, files } = await loadGenerated();
const result = validateDataset({
  manifest,
  files,
  collections: COLLECTIONS,
  metrics: METRICS,
  sources: SOURCES,
  allowedLicences: ALLOWED_LICENCES,
});
type Exclusions = Record<string, Record<string, { count: number; examples: string[] }>>;
let exclusions: Exclusions = {};
try {
  exclusions = JSON.parse(await readFile('data/exclusions.json', 'utf8')) as Exclusions;
} catch {
  // Exclusion log is optional (written by data:build).
}

const n = (x: number) => x.toLocaleString('en-GB');
const fmt = (x: number) => {
  const abs = Math.abs(x);
  if (abs !== 0 && (abs >= 1e7 || abs < 0.01)) return x.toExponential(2);
  return x.toLocaleString('en-GB', { maximumFractionDigits: 2 });
};
const s = result.stats;
const lines: string[] = [];
const push = (...xs: string[]) => lines.push(...xs);

push(
  '# UPDOWNLY — Data coverage',
  '',
  `_Generated by \`npm run data:report\` from the bundled dataset. Dataset version **${manifest.dataVersion}**, built ${manifest.generatedAt}._`,
  '',
  '## Totals',
  '',
  '| Measure | Value |',
  '|---|---|',
  `| Distinct observations (entity × metric × period) | **${n(s.totalFacts)}** |`,
  `| Unique entities | ${n(s.totalEntities)} |`,
  `| Playable collections | ${s.collections} |`,
  `| Category groups | ${s.groups} |`,
  `| Independent sources | ${manifest.sources.length} |`,
  `| Validation | ${result.errors.length === 0 ? 'passed' : `**${result.errors.length} errors**`} (${result.warnings.length} warnings) |`,
  '',
  'Every observation is one source value for one entity, one metric and one reference period. Nothing is duplicated, generated or estimated by UPDOWNLY; unit conversions are listed per metric below.',
  '',
  '## Collections',
  '',
  '| Group | Collection | Facts | Reference period | Source | Range | Tie probability |',
  '|---|---|---:|---|---|---|---:|',
);
for (const g of GROUPS) {
  for (const def of COLLECTIONS.filter((c) => c.groupId === g.id)) {
    const m = manifest.collections.find((c) => c.id === def.id)!;
    const st = s.perCollection.find((c) => c.id === def.id)!;
    const metric = metricById(def.metricId)!;
    const src = SOURCES.find((x) => x.id === def.sourceId)!;
    push(
      `| ${g.title} | ${def.title} · ${def.subtitle} (\`${def.id}\`) | ${n(m.count)} | ${m.periodLabel} | ${src.name} | ${fmt(m.min)} – ${fmt(m.max)} ${metric.unitLabel} | ${st.tieProbability.toFixed(3)} |`,
    );
  }
}

push('', '## Sources and licences', '');
for (const src of manifest.sources) {
  const used = COLLECTIONS.filter((c) => c.sourceId === src.id);
  const count = used.reduce((a, c) => a + (manifest.collections.find((x) => x.id === c.id)?.count ?? 0), 0);
  push(
    `### ${src.name}`,
    '',
    `- Link: ${src.url}`,
    `- Licence: [${src.licence}](${src.licenceUrl})`,
    `- Attribution: ${src.attribution}`,
    `- Retrieved: ${src.retrievedAt}${src.datasetVersion ? ` · Version: ${src.datasetVersion}` : ''}`,
    `- Collections: ${used.length} · Observations: ${n(count)}`,
    '',
  );
}

push('## Metric definitions and conversions', '', '| Metric | Unit | What is compared | Method / conversion |', '|---|---|---|---|');
for (const m of METRICS) {
  if (!COLLECTIONS.some((c) => c.metricId === m.id)) continue;
  push(`| ${m.label} (\`${m.id}\`) | ${m.unitLabel || m.unit} | ${m.comparisonDescription} | ${m.methodologyNote ?? '—'} |`);
}

push(
  '',
  '## Exclusions',
  '',
  'Observations rejected by the pipeline, with the reason. Nothing is silently dropped: every rejection is counted here (examples in `data/exclusions.json`).',
  '',
  '| Collection | Reason | Excluded |',
  '|---|---|---:|',
);
for (const def of COLLECTIONS) {
  const reasons = Object.entries(exclusions[def.id] ?? {}).sort((a, b) => b[1].count - a[1].count);
  for (const [reason, e] of reasons) push(`| \`${def.id}\` | ${reason} | ${n(e.count)} |`);
}

push(
  '',
  '## Quality rules',
  '',
  '- Each collection is exactly one comparison group: one metric, one unit, one reference period and one source. The game never compares across collections.',
  '- World Bank collections are pinned to the most recent year with at least 85 % of the best country coverage since 2010; regional and income aggregates are excluded.',
  '- Wikidata collections require an English label and English Wikipedia article plus a per-collection notability threshold (Wikipedia language editions). Deprecated statements and part-of-entity statements (P518) are ignored; a preferred statement wins; otherwise conflicting values (> 0.5 % apart) exclude the entity.',
  '- Skyscrapers must show evidence of completion (opening date or “in use” state); heights and floor counts are cross-checked (2.4–8 m per floor).',
  '- Exoplanet values the archive marks as calculated are excluded; planet mass uses true masses only.',
  '- Food nutrients are per 100 g edible portion. Zero amounts are excluded because a 0 g reference makes the next answer certain.',
  '- Animals need a common name and a notability threshold (Wikipedia language editions) so the game uses species people can picture.',
  '- Ties are never asked: the game engine skips pairs whose values — or displayed values — are equal.',
  '',
  '## Limitations and incomplete areas',
  '',
  '- **City populations** are not included: no openly licensed source with one consistent reference period was reachable when the dataset was built (UN WUP download links have moved; the US Census API was unreachable). Wikidata city populations mix census years, so they were not used.',
  '- **Aircraft and vehicle specifications** are not included: no openly licensed structured dataset with consistent measurement definitions was found.',
  '- **Wikidata-derived values** (geography, structures, venues, films) reflect community-maintained records. Conflicting records are excluded, but a single wrong record cannot always be detected.',
  '- **Food data** is the final SR Legacy release (2018). It is still the most complete open per-100 g reference but will not reflect newer reformulations.',
  '- **Amniote life-history data** dates from 2015; maximum-longevity records may since have been exceeded.',
  '- Statistical outliers are flagged for review but never removed automatically:',
  ...s.perCollection.filter((c) => c.outliers > 0).map((c) => `  - \`${c.id}\`: ${c.outliers} value(s) beyond 3×IQR on a log scale`),
  '',
);

await writeFile('DATA-COVERAGE.md', lines.join('\n'));
console.log(`DATA-COVERAGE.md written (${n(s.totalFacts)} facts, ${s.collections} collections).`);
